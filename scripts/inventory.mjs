#!/usr/bin/env node
// Write plugin-files.json: every file of the FCWM plugin with its SHA-256, so an agent that rebuilds
// the plugin file by file (ChatGPT Work, see INSTALL.md) can prove each copy is exact before packing.
//
//   node scripts/inventory.mjs          write plugin-files.json
//   node scripts/inventory.mjs --check  exit 1 if plugin-files.json is out of date (used by validate)
//
// Hashes are taken over the file as stored in git (LF line endings), so a Windows checkout with CRLF
// gives the same result. Groups:
//   core   manifests and skills: the plugin works with these alone
//   extra  blocks, recipes, templates and knowledge the skills read; install them when you can
//   skip   binaries and tests: an agent that rewrites files as text leaves them out
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'plugin-files.json';

// The same set as the upload ZIP in docs/install-chatgpt.md.
export const INCLUDE = ['plugin.json', '.claude-plugin', '.codex-plugin', 'skills', 'LICENSE', 'NOTICE', 'INSTALL.md',
  'AGENTS.md', 'README.md', 'lib', 'recipes', 'templates', 'knowledge', 'brand-kit', 'engines/catalog.json',
  'integrations', 'qa/README.md'];
const CORE = /^(plugin\.json|\.claude-plugin\/|\.codex-plugin\/|skills\/|LICENSE$|NOTICE$|INSTALL\.md$)/;
const TEST = /(^|\/)test\//;

function tracked() {
  const out = execFileSync('git', ['ls-files', '-z', '--', ...INCLUDE], { cwd: ROOT, encoding: 'utf8' });
  return out.split('\0').filter(Boolean).sort();
}

export function build() {
  const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
  const files = tracked().map((p) => {
    let data = fs.readFileSync(path.join(ROOT, p));
    const binary = data.includes(0) || /\.(jpe?g|png|gif|webp|woff2?|ttf|otf|mp4|mov|wav|mp3|zip)$/i.test(p);
    if (!binary) data = Buffer.from(data.toString('utf8').replace(/\r\n/g, '\n'), 'utf8');
    const group = binary || TEST.test(p) ? 'skip' : CORE.test(p) ? 'core' : 'extra';
    const entry = { path: p, sha256: crypto.createHash('sha256').update(data).digest('hex'), bytes: data.length, group };
    if (group === 'skip') entry.reason = binary ? 'binary' : 'test';
    return entry;
  });
  const total = (g) => files.filter((f) => f.group === g).reduce((n, f) => n + f.bytes, 0);
  return {
    name: 'fcwm',
    version,
    repository: 'https://github.com/FrameCoreWorks/FCWM',
    note: 'Generated by scripts/inventory.mjs. SHA-256 over the file as stored in git (LF). Groups: core (required), extra (recommended), skip (binary or test). See INSTALL.md.',
    bytes: { core: total('core'), extra: total('extra'), skip: total('skip') },
    files,
  };
}

export const render = () => JSON.stringify(build(), null, 1) + '\n';

export function stale() {
  const file = path.join(ROOT, OUT);
  if (!fs.existsSync(file)) return true;
  return fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== render();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (stale()) { console.error(`${OUT} is out of date: run node scripts/inventory.mjs`); process.exit(1); }
    console.log(`${OUT}: up to date`);
  } else {
    fs.writeFileSync(path.join(ROOT, OUT), render());
    const b = build();
    console.log(`${OUT}: ${b.files.length} files (core ${b.bytes.core} B, extra ${b.bytes.extra} B, skip ${b.bytes.skip} B)`);
  }
}
